// npm run inventory  -> writes docs/content-inventory.json (what content exists right now + the rules to follow).
import { writeFileSync } from 'node:fs'
import { readFileSync } from 'node:fs'
import { LIMITS, validateContent } from '../src/content/validate.ts'

const read = (f: string) => JSON.parse(readFileSync(new URL(`../src/content/${f}`, import.meta.url), 'utf8'))
const words = read('words.json') as { hanzi: string; pinyin: string; meaning: string; group: string; note: string; alt?: string[]; confusable?: string[]; lookalike?: string[] }[]
const explanations = read('explanations.json') as Record<string, { title?: string; summary: string; sections: { type: string; heading?: string }[]; related?: string[] }>
const { errors, warnings } = validateContent(words, explanations)

const groups: Record<string, string[]> = {}
for (const w of words) (groups[w.group] ??= []).push(w.hanzi)

const inventory = {
  _about: 'Generated by `npm run inventory` from src/content/*.json. Do not edit by hand; edit the source files and regenerate.',
  generatedFrom: ['src/content/words.json', 'src/content/explanations.json'],
  guide: 'docs/CONTENT_GUIDE.md',
  stats: {
    words: words.length,
    explanations: Object.keys(explanations).length,
    wordsWithoutExplanation: words.filter(w => !explanations[w.hanzi]).length,
    validatorErrors: errors.length,
    validatorWarnings: warnings.length
  },
  teachingOrder: words.map(w => w.hanzi).join(''),
  groups,
  limits: LIMITS,
  words: words.map((w, i) => ({
    order: i + 1, hanzi: w.hanzi, pinyin: w.pinyin, meaning: w.meaning, group: w.group,
    ...(w.alt ? { alt: w.alt } : {}), ...(w.confusable ? { confusable: w.confusable } : {}), ...(w.lookalike ? { lookalike: w.lookalike } : {}),
    hasExplanation: w.hanzi in explanations
  })),
  explanations: Object.entries(explanations).map(([hanzi, e]) => ({
    hanzi, title: e.title ?? `About ${hanzi}`, summary: e.summary,
    sectionTypes: e.sections.map(s => s.type), related: e.related ?? []
  })),
  existingIssues: { errors, warnings }
}
writeFileSync(new URL('../docs/content-inventory.json', import.meta.url), JSON.stringify(inventory, null, 2) + '\n')
console.log(`docs/content-inventory.json: ${words.length} words, ${Object.keys(explanations).length} explanations`)
