// npm run inventory  -> writes docs/content-inventory.json (what content exists right now + the rules to follow).
import { writeFileSync } from 'node:fs'
import { readFileSync } from 'node:fs'
import { LIMITS, needsReview, validateContent } from '../src/content/validate.ts'

const read = (f: string) => JSON.parse(readFileSync(new URL(`../src/content/${f}`, import.meta.url), 'utf8'))
type RawEntry = { id?: string; hanzi: string; pinyin: string; meaning: string; group: string; note: string; kind?: string; neutral?: number[]; variants?: string[]; speech?: unknown[]; wrongPinyin?: string[]; audio?: string; questions?: string[]; aliases?: string[]; confusable?: string[]; lookalike?: string[]; review?: { status: string } }
const words = read('words.json') as RawEntry[]
const explanations = read('explanations.json') as Record<string, { title?: string; summary: string; sections: { type: string; heading?: string }[]; related?: string[] }>
const cloze = read('cloze.json') as { id: string; answer: string; zh: string; options: string[] }[]
const sources = read('sources.json') as Record<string, unknown>
const { errors, warnings } = validateContent(words, explanations, cloze, sources)
const idOf = (w: RawEntry) => w.id ?? w.hanzi
const review = needsReview(words, explanations, cloze)

const groups: Record<string, string[]> = {}
for (const w of words) (groups[w.group] ??= []).push(w.hanzi)

const inventory = {
  _about: 'Generated by `npm run inventory` from src/content/*.json. Do not edit by hand; edit the source files and regenerate.',
  generatedFrom: ['src/content/words.json', 'src/content/explanations.json', 'src/content/cloze.json', 'src/content/sources.json'],
  guide: 'docs/CONTENT_GUIDE.md',
  stats: {
    entries: words.length,
    explanations: Object.keys(explanations).length,
    sentenceQuestions: cloze.length,
    entriesWithoutExplanation: words.filter(w => !explanations[idOf(w)]).length,
    notReviewedByAPerson: { entries: review.words.length, exampleSentences: review.examples.length, sentenceQuestions: review.cloze.length },
    validatorErrors: errors.length,
    validatorWarnings: warnings.length
  },
  teachingOrder: words.map(w => w.hanzi).join(' '),
  groups,
  sourceNames: Object.keys(sources),
  limits: LIMITS,
  entries: words.map((w, i) => ({
    order: i + 1, id: idOf(w), hanzi: w.hanzi, pinyin: w.pinyin, meaning: w.meaning, group: w.group,
    kind: w.kind ?? ([...w.hanzi].length > 1 ? 'word' : 'character'),
    ...(w.neutral ? { neutral: w.neutral } : {}), ...(w.variants ? { variants: w.variants } : {}), ...(w.speech ? { speech: w.speech.length } : {}),
    ...(w.wrongPinyin ? { wrongPinyin: w.wrongPinyin } : {}), ...(w.audio ? { audio: w.audio } : {}), ...(w.questions ? { questions: w.questions } : {}),
    ...(w.aliases ? { aliases: w.aliases } : {}), ...(w.confusable ? { confusable: w.confusable } : {}), ...(w.lookalike ? { lookalike: w.lookalike } : {}),
    review: w.review?.status ?? 'none', hasExplanation: idOf(w) in explanations
  })),
  explanations: Object.entries(explanations).map(([id, e]) => ({
    id, title: e.title ?? `About ${id}`, summary: e.summary,
    sectionTypes: e.sections.map(s => s.type), related: e.related ?? []
  })),
  sentenceQuestions: cloze.map(c => ({ id: c.id, answer: c.answer, zh: c.zh, options: c.options })),
  existingIssues: { errors, warnings }
}
writeFileSync(new URL('../docs/content-inventory.json', import.meta.url), JSON.stringify(inventory, null, 2) + '\n')
console.log(`docs/content-inventory.json: ${words.length} entries, ${Object.keys(explanations).length} explanations, ${cloze.length} sentence questions`)
